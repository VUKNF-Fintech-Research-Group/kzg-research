#!/usr/bin/env python3
"""report.py — writes eval/reports/results.md from the processed CSVs (Q15: no hand-typed numbers).

Usage (repo root): .venv/bin/python eval/scripts/report.py
Run after aggregate.py and qc.py.
"""
import csv
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
EVAL = REPO / "eval"
PROC = EVAL / "data" / "processed"


def rows(name):
    return list(csv.DictReader(open(PROC / name)))


def g(v):
    return f"{float(v):,.0f}"


def main():
    man = json.loads((EVAL / "reports" / "manifest.json").read_text())
    qc = json.loads((PROC / "qc.json").read_text())
    vs = [r for r in rows("verify_summary.csv") if r["state"] == "seeded"]
    real = {(r["sut"], r["N"]): r for r in rows("verify_summary.csv") if r["state"] == "real"}
    up = rows("update_summary.csv")
    batch = rows("batch.csv")
    neg = rows("negatives.csv")
    ratios = rows("ratios.csv")
    cost = rows("cost_usd.csv")
    by = {(r["sut"], r["N"]): r for r in vs}
    ns = sorted({int(r["N"]) for r in vs})

    L = ["# EXP-001 results — S1 and S2 on Hardhat", "",
         f"Generated by `eval/scripts/report.py` on {man['generated_utc'][:16]} UTC from `eval/data/processed/`. "
         f"Commit `{man['git_commit'][:7]}` on `{man['git_branch']}`{' (uncommitted changes)' if man['dirty'] else ''}. "
         f"Network: Hardhat {man['hardhat']}, hardfork Prague, real EIP-2537 precompiles. solc {man['compiler'].get('solc')}, "
         f"optimizer {man['compiler'].get('optimizer')}, EVM target {man['compiler'].get('evmVersion')}. {man['cpu']}, {man['os']}.", "",
         "**Scope.** Only S1 (Merkle, revealed ID) and S2 (KZG, revealed ID). S3–S6 are not in this repository yet. "
         "Both designs are *revocation only*. No Hoodi rows yet (Gate B), no off-chain timing yet.", "",
         f"**QC gate A for S1/S2: {'PASS' if qc['gate_A_S1_S2'] else 'FAIL'}.** Full table: `eval/reports/qc-report.md`.", "",
         "## E1 — Verify gas against N (M1, median of 10 fresh proofs, seeded state)", "",
         "| N | S1 M1 | S1 range | S1 proof bytes | S1 floor binds | S2 M1 | S2 range | S2 / S1 |", "|---:|---:|---:|---:|---:|---:|---:|---:|"]
    rmap = {r["N"]: r for r in ratios}
    for n in ns:
        a, b = by[("S1", str(n))], by[("S2", str(n))]
        L.append(f"| {n:,} | {g(a['M1_median_gas'])} | {g(a['M1_min_gas'])}–{g(a['M1_max_gas'])} | {g(a['M5_proof_bytes_median'])} | "
                 f"{float(a['floor_binds_share']):.0%} | {g(b['M1_median_gas'])} | {g(b['M1_min_gas'])}–{g(b['M1_max_gas'])} | {float(rmap[str(n)]['value']):.2f}× |")
    L += ["", "S2 / S1 uses S1's median as the base. S2's proof is 160 bytes (w 128 + y 32) at every N.", "",
          "**Real path.** At N = 16 and 256 the registries were also built one revocation at a time through the production entry point. The stored state equals the seeded state (Q11), and the verify gas medians are identical: " +
          "; ".join(f"{s} N={n}: {g(real[(s, n)]['M1_median_gas'])}" for (s, n) in sorted(real)) + ".", "",
          "## Where the gas goes (M2–M4, medians)", "",
          "| Design | N | M1 | Base | Calldata M3 | Precompiles M2 (traced) | Execution remainder M4 | EIP-7623 floor | Floor binds |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for n in ns:
        for s in ("S1", "S2"):
            r = by[(s, str(n))]
            L.append(f"| {s} | {n:,} | {g(r['M1_median_gas'])} | 21,000 | {g(r['M3_calldata_median_gas'])} | {g(r['M2_precompile_gas'])} | "
                     f"{g(r['M4_exec_remainder_median_gas'])} | {g(r['floor_gas_median'])} | {float(r['floor_binds_share']):.0%} |")
    s2 = by[("S2", str(ns[0]))]
    L += ["", f"S2's traced precompile gas is {g(s2['M2_precompile_gas'])} on every row, equal to the EIP-2537 formula "
          f"({g(s2['M2_formula_gas'])}: one 3-point G1MSM and one 2-pair pairing check). "
          "When the EIP-7623 floor binds (S1 from N = 256), gasUsed equals the floor (21,000 + 10 × calldata tokens) and execution no longer changes the price.", "",
          "## E3 — Revocation update gas (M6, median of 5)", "", "| N | S1 first | S1 later | S2 first | S2 later |", "|---:|---:|---:|---:|---:|"]
    um = {(r["sut"], r["N"], r["kind"]): r["M6_median_gas"] for r in up}
    for n in ns:
        L.append(f"| {n:,} | {g(um[('S1', str(n), 'update_first')])} | {g(um[('S1', str(n), 'update_later')])} | "
                 f"{g(um[('S2', str(n), 'update_first')])} | {g(um[('S2', str(n), 'update_later')])} |")
    L += ["", "Both entry points overwrite the whole state (root: 1 storage word; C: 4 words), so first and later updates cost the same. "
          "Only the new root or commitment goes on-chain; publishing the revoked handles for holders is not included.", "",
          f"**S2 batch (base N = {batch[0]['base_N']}), transaction amortisation, not a KZG property:**", "",
          "| k | k updates, total | 1 update | Gain |", "|---:|---:|---:|---:|"]
    for r in batch:
        L.append(f"| {r['k']} | {g(r['incremental_total_gas'])} | {g(r['batch_gas_median'])} | {float(r['gain_pct']):.2f}% |")
    L += ["", f"Gain = {batch[0]['gain_formula']}.", "", "## E7 — Negative tests", "",
          "| Design | Cases per N | Sizes | All rejected | Reverted | Logged ok = false |", "|---|---:|---:|---|---:|---:|"]
    for s in ("S1", "S2"):
        rs = [r for r in neg if r["sut"] == s]
        cases = sorted({r["case"] for r in rs})
        L.append(f"| {s} | {len(cases)} | {len({r['N'] for r in rs})} | {'yes' if all(r['pass'] == 'True' for r in rs) else 'NO'} | "
                 f"{sum(r['outcome'] == 'revert' for r in rs)} | {sum(r['outcome'] == 'ok=false' for r in rs)} |")
    L += ["", "Cases: " + "; ".join(f"**{s}** " + ", ".join(sorted({r['case'] for r in neg if r['sut'] == s})) for s in ("S1", "S2")) + ".", "",
          "## E8 — Cost per verification (M12, N = 1,024)", "", "| Design | " + " | ".join(f"{p} gwei" for p in sorted({int(r['gas_price_gwei']) for r in cost})) + " |",
          "|---|" + "---:|" * len({r['gas_price_gwei'] for r in cost})]
    for s in ("S1", "S2"):
        cs = sorted((r for r in cost if r["sut"] == s and r["N"] == "1024"), key=lambda r: int(r["gas_price_gwei"]))
        L.append(f"| {s} | " + " | ".join(f"${float(r['usd_per_verification']):.3f}" for r in cs) + " |")
    L += ["", f"ETH price {cost[0]['eth_price_usd']} USD, a fixed assumption in `eval/config/cost.json`, not a quote.", "",
          "## Figures", "", "- `eval/figures/V1_verify_gas_vs_N.{png,svg,csv}`", "- `eval/figures/V2_gas_breakdown.{png,svg,csv}`", "- `eval/figures/V7_cost_usd.{png,svg,csv}`", "",
          "## Deviations from the reference values", "", next(c["detail"] for c in qc["checks"] if c["id"] == "Q16"), "",
          next(c["detail"] for c in qc["checks"] if c["id"] == "RF"), ""]
    (EVAL / "reports" / "results.md").write_text("\n".join(L) + "\n")
    print("wrote eval/reports/results.md")


if __name__ == "__main__":
    main()
