#!/usr/bin/env python3
"""gen_kzg_fixtures.py

Generate real KZG commitments and opening proofs for the Solidity tests, in
the EIP-2537 encoding the contract expects.

Usage:
    python3 scripts/gen_kzg_fixtures.py

Writes:
    test/fixtures/kzg_revocation.json   small sets for the unit tests
    test/fixtures/kzg_gas_sweep.json    one set per degree for the gas benchmark
    test/fixtures/kzg_batch_sweep.json  commitments for the batch-revocation benchmark

The output is deterministic. test/python/test_fixtures.py fails if the
committed files no longer match what this script produces.
"""
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "bindings" / "python"))

import eip2537  # noqa: E402
import oneProofOffChain_KZG as kzg  # noqa: E402

TS_PATH = REPO_ROOT / "src" / "trusted_setup.txt"
FIXTURE_PATH = REPO_ROOT / "test" / "fixtures" / "kzg_revocation.json"
SWEEP_PATH = REPO_ROOT / "test" / "fixtures" / "kzg_gas_sweep.json"

BATCH_PATH = REPO_ROOT / "test" / "fixtures" / "kzg_batch_sweep.json"

# Largest batch in the batch-revocation benchmark.
BATCH_MAX = 100

# Number of revoked IDs (= polynomial degree) per benchmark point. 4095 is the
# largest degree the EIP-4844 SRS supports.
SWEEP_DEGREES = [2, 16, 256, 1024, 4095]

# name -> (revoked IDs, IDs to open at)
SETS = {
    "empty": ([], [5]),
    "base": ([3, 7, 9], [5, 11, 12345, 3, 7, 9]),
    "updated": ([3, 7, 9, 11], [5, 11]),
}


def hx(b: bytes) -> str:
    return "0x" + bytes(b).hex()


def build_set(revoked, open_at, ts) -> dict:
    """Commitment to prod(x - id) over `revoked`, plus an opening at each z."""
    poly = kzg.build_revoked_poly(revoked)
    commitment = bytes(kzg.kzg_commit_from_coeffs(poly, ts))
    openings = []
    for z in open_at:
        proof, y = kzg.compute_kzg_proof_from_coeffs(poly, z, ts)
        proof = bytes(proof)
        assert y == kzg.evaluate_revoked_poly(revoked, z)
        openings.append({
            "z": str(z),
            "y": str(y),
            "revoked": z in revoked,
            "w_compressed": hx(proof),
            "w": hx(eip2537.g1_to_eip2537(proof)),
            "offchain_verifies": kzg.verify_kzg_proof(commitment, proof, z, y, ts),
        })
    return {
        "revoked_ids": [str(r) for r in revoked],
        "commitment_compressed": hx(commitment),
        "commitment": hx(eip2537.g1_to_eip2537(commitment)),
        "openings": openings,
    }


def _opening(poly, commitment, revoked, z, ts) -> dict:
    proof, y = kzg.compute_kzg_proof_from_coeffs(poly, z, ts)
    proof = bytes(proof)
    assert y == kzg.evaluate_revoked_poly(revoked, z)
    return {
        "z": str(z),
        "y": str(y),
        "revoked": z in revoked,
        "w": hx(eip2537.g1_to_eip2537(proof)),
        "offchain_verifies": kzg.verify_kzg_proof(commitment, proof, z, y, ts),
    }


def build_sweep_point(degree: int, ts) -> dict:
    """Inputs for one benchmark point with `degree` revoked IDs.

    Revoked IDs are 1..degree. `next_commitment` is the commitment after one
    more ID changes (degree stays the same), used to measure updateCommitment().
    """
    revoked = list(range(1, degree + 1))
    shared = kzg.build_revoked_poly(revoked[:-1])
    poly = kzg.poly_mul(shared, [-revoked[-1], 1])
    commitment = bytes(kzg.kzg_commit_from_coeffs(poly, ts))

    next_revoked = revoked[:-1] + [degree + 1]
    next_poly = kzg.poly_mul(shared, [-next_revoked[-1], 1])
    next_commitment = bytes(kzg.kzg_commit_from_coeffs(next_poly, ts))

    valid_z = 10 * degree + 7  # not in either revoked set
    return {
        "degree": degree,
        "revoked_ids": f"1..{degree}",
        "commitment": hx(eip2537.g1_to_eip2537(commitment)),
        "commitment_compressed": hx(commitment),
        "next_commitment": hx(eip2537.g1_to_eip2537(next_commitment)),
        "valid": _opening(poly, commitment, revoked, valid_z, ts),
        "other_valid": _opening(poly, commitment, revoked, valid_z + 1, ts),
        "revoked": _opening(poly, commitment, revoked, revoked[0], ts),
    }


def build_sweep() -> dict:
    ts = kzg.load_trusted_setup(str(TS_PATH), 0)
    return {
        "description": "Generated by scripts/gen_kzg_fixtures.py. Do not edit by hand.",
        "scalar_modulus": str(kzg.BLS_MODULUS),
        "points": [build_sweep_point(d, ts) for d in SWEEP_DEGREES],
    }


def build_batch() -> dict:
    """Commitments to the revoked sets {}, {1}, {1, 2}, ..., {1..BATCH_MAX}.

    commitments[i] is the commitment after i revocations. Revoking k IDs one
    transaction at a time walks commitments[1..k]; a single batch update jumps
    from commitments[0] straight to commitments[k].
    """
    ts = kzg.load_trusted_setup(str(TS_PATH), 0)
    poly = [1]
    commitments = []
    for i in range(BATCH_MAX + 1):
        if i > 0:
            poly = kzg.poly_mul(poly, [-i, 1])
        commitments.append(hx(eip2537.g1_to_eip2537(bytes(kzg.kzg_commit_from_coeffs(poly, ts)))))
    return {
        "description": "Generated by scripts/gen_kzg_fixtures.py. Do not edit by hand.",
        "revoked_ids": "commitments[i] commits to the revoked set {1..i}",
        "commitments": commitments,
    }


def build_fixtures() -> dict:
    ts = kzg.load_trusted_setup(str(TS_PATH), 0)
    return {
        "description": "Generated by scripts/gen_kzg_fixtures.py. Do not edit by hand.",
        "encoding": "EIP-2537 uncompressed (G1 = 128 bytes); *_compressed fields are the 48-byte c-kzg form",
        "scalar_modulus": str(kzg.BLS_MODULUS),
        "sets": {name: build_set(revoked, open_at, ts) for name, (revoked, open_at) in SETS.items()},
    }


def main():
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    for path, data in (
        (FIXTURE_PATH, build_fixtures()),
        (SWEEP_PATH, build_sweep()),
        (BATCH_PATH, build_batch()),
    ):
        path.write_text(json.dumps(data, indent=2) + "\n")
        print(f"wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
